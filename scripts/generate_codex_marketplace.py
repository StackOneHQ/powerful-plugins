@dataclass(frozen=True)
class ExternalSource:
    """A Claude external plugin source, pinned to one upstream commit."""

    repo: str
    path: str | None
    sha: str


_EXTERNAL_SOURCE_KEYS = {
    "github": {"source", "repo", "sha"},
    "git-subdir": {"source", "url", "path", "sha"},
}


def parse_external_source(source: dict[str, object]) -> ExternalSource:
    """Validate a Claude external source and return its repository, path and commit.

    A repository-root plugin uses ``github`` with ``repo`` and ``sha``. A plugin in a
    subdirectory uses ``git-subdir`` with ``url`` (``owner/repo``), ``path`` and ``sha``.
    Claude Code ignores ``path`` on a ``github`` source and installs the whole repository,
    and a ``ref`` names a branch or tag that can move, so both are rejected.
    """
    kind = source.get("source")
    if not isinstance(kind, str) or kind not in _EXTERNAL_SOURCE_KEYS:
        raise GenerationError(
            f"unsupported external source: {kind!r}; use github or git-subdir"
        )
    if kind == "github" and "path" in source:
        raise GenerationError(
            "a github source cannot select a subdirectory: Claude Code ignores its path "
            "and installs the whole repository; use git-subdir with url, path and sha"
        )
    if "ref" in source:
        raise GenerationError(
            "external sources pin a commit with sha, not ref; a ref is a branch or tag "
            "and can move"
        )
    allowed = _EXTERNAL_SOURCE_KEYS[str(kind)]
    missing = sorted(allowed - set(source))
    unknown = sorted(set(source) - allowed)
    if missing or unknown:
        raise GenerationError(
            f"{kind} source must contain exactly {', '.join(sorted(allowed))} "
            f"(missing: {missing}, unexpected: {unknown})"
        )

    repo = source["repo" if kind == "github" else "url"]
    if not isinstance(repo, str) or not GITHUB_REPOSITORY_PATTERN.fullmatch(repo):
        raise GenerationError("external GitHub source must name an owner/repository")
    owner, repository = repo.split("/", 1)
    if (
        owner.endswith("-")
        or repository in {".", ".."}
        or repository.startswith(".")
        or repository.endswith((".", "-", ".git"))
    ):
        raise GenerationError("external GitHub source must include a safe owner/repository")

    sha = source["sha"]
    if not isinstance(sha, str) or not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise GenerationError(
            "external source sha must be a full 40-character lowercase commit SHA"
        )

    path = source.get("path")
    if path is None:
        return ExternalSource(repo, None, sha)
    if (
        not isinstance(path, str)
        or not path
        or path != path.strip()
        or path.startswith(("/", "./"))
        or path.endswith("/")
        or "//" in path
    ):
        raise GenerationError("external source path must be a non-empty relative path")
    if "\\" in path:
        raise GenerationError("external source path must use POSIX separators")
    if any(part in {"", ".", ".."} for part in PurePosixPath(path).parts):
        raise GenerationError("external source path must stay inside the repository")
    return ExternalSource(repo, path, sha)


def convert_source(source: dict[str, object]) -> dict[str, object]:
    """Convert a pinned Claude external source into the Codex source for the same commit."""
    parsed = parse_external_source(source)
    converted: dict[str, object] = {
        "source": "url" if parsed.path is None else "git-subdir",
        "url": f"https://github.com/{parsed.repo}.git",
    }
    if parsed.path is not None:
        converted["path"] = f"./{parsed.path}"
    converted["ref"] = parsed.sha
    return converted


def normalize_category(value: str) -> str:
    """Convert marketplace category slugs into human-facing labels."""
    if not isinstance(value, str) or not value.strip():
        raise GenerationError("plugin category must be a non-empty string")
    return " ".join(part.capitalize() for part in re.split(r"[-_\s]+", value.strip()))


def resolve_local_source(root: Path, source: str) -> Path:
    """Resolve a ./-prefixed marketplace source without permitting traversal."""
    if not isinstance(source, str) or not source.startswith("./"):
        raise GenerationError("local plugin source must start with './'")

    resolved_root = root.resolve()
    candidate = (resolved_root / source[2:]).resolve()
    if not candidate.is_relative_to(resolved_root):
        raise GenerationError(f"local plugin source is outside the repository: {source}")
    return candidate


